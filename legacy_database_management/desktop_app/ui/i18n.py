def get_text(key: str, lang: str = "en", *args) -> str:
    """Get translated text for a key, optionally formatted with args."""
    text = TEXTS.get(lang, TEXTS["en"]).get(key, key)
    if args:
        text = text.format(*args)
    return text


def t(lang: str):
    """Return a translation function bound to the given language."""
    def translate(key: str, *args) -> str:
        return get_text(key, lang, *args)
    return translate
